"""Build the Gambito site so it runs straight from disk (double-click index.html) as well as hosted.

Browsers block three things on pages opened from disk (file://): ES-module scripts, fetch() of local
files, and Web Workers from file URLs. So this script makes:
  1. app/gambito.js  : app/src/*.js (ES modules) + lib/chess.js bundled into one classic script (esbuild).
  2. data/*.js       : any data/*.json left over is converted to window.GAMBITO_DATA[name] = {...}.
                       (site_data.py writes .js directly.)
  3. lib/sf-embed.js : the Stockfish worker source (patched to read its wasm from self.__SFW) and the
                       wasm as base64. On file:// the app starts the worker from a blob: URL.
Then it checks that every data file parses and that the band index matches the band files.

Usage:  py -B site_build.py      (after editing app/src/*.js, or after site_data.py)
"""
import base64, glob, json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
from paths import SITE_DIR
SITE = SITE_DIR
from paths import ESBUILD
SF = "stockfish-19-lite-single"
JS_PREFIX = "window.GAMBITO_DATA=window.GAMBITO_DATA||{};window.GAMBITO_DATA[%s]="
BANNER = ("/* Gambito: generated by site_build.py from app/src/*.js. Edit those, then rebuild. "
          "Includes chess.js (BSD-2-Clause, Jeff Hlywa). Licences: LICENSES.txt */ 'use strict';")


def data_prefix(name):
    return JS_PREFIX % json.dumps(name)


def write_data_js(path, obj):
    """data/<name>.js = window.GAMBITO_DATA["<name>"] = <compact JSON>; (loaded by a <script> tag)."""
    name = os.path.splitext(os.path.basename(path))[0]
    with open(path, "w", encoding="utf-8") as f:
        f.write(data_prefix(name) + json.dumps(obj, separators=(",", ":")) + ";\n")


def read_data_js(path):
    name = os.path.splitext(os.path.basename(path))[0]
    s = open(path, encoding="utf-8").read()
    pre = data_prefix(name)
    assert s.startswith(pre), f"{path}: unexpected header"
    return json.loads(s[len(pre):].rstrip().rstrip(";"))


def convert_json():
    n = 0
    for p in sorted(glob.glob(os.path.join(SITE, "data", "*.json"))):
        name = os.path.splitext(os.path.basename(p))[0]
        obj = json.load(open(p, encoding="utf-8"))
        out = p[:-5] + ".js"
        write_data_js(out, obj)
        assert read_data_js(out) == obj, f"{name}.js: round-trip mismatch"
        os.remove(p)
        n += 1
    print(f"data: converted {n} .json file(s) to .js")


def engine_embed():
    lib = os.path.join(SITE, "lib")
    src = open(os.path.join(lib, SF + ".js"), encoding="utf-8").read()
    needle = r'a[0]||location.origin+location.pathname.replace(/\.js$/i,".wasm")'
    assert src.count(needle) == 1, "stockfish.js changed: the wasm-path hook was not found"
    src = src.replace(needle, "self.__SFW||" + needle)
    wasm = base64.b64encode(open(os.path.join(lib, SF + ".wasm"), "rb").read()).decode()
    out = os.path.join(lib, "sf-embed.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* Stockfish 19 lite (GPL-3.0; see COPYING-stockfish.txt and LICENSES.txt), packed by site_build.py\n"
                "   for pages opened from disk: the worker source, patched to read its wasm from self.__SFW,\n"
                "   and the unchanged " + SF + ".wasm as base64. */\n")
        f.write("window.SF_SRC=" + json.dumps(src) + ";\n")
        f.write('window.SF_WASM_B64="' + wasm + '";\n')
    print(f"engine: lib/sf-embed.js {os.path.getsize(out) // 1024} KB")


def bundle():
    out = os.path.join(SITE, "app", "gambito.js")
    subprocess.run([ESBUILD, "app/src/main.js", "--bundle", "--format=iife", "--legal-comments=eof",
                    "--banner:js=" + BANNER, "--outfile=app/gambito.js", "--log-level=warning"],
                   check=True, cwd=SITE)
    print(f"bundle: app/gambito.js {os.path.getsize(out) // 1024} KB")


def check():
    bad = []
    files = sorted(glob.glob(os.path.join(SITE, "data", "*.js")))
    names = {os.path.splitext(os.path.basename(p))[0] for p in files}
    for p in files:
        try:
            read_data_js(p)
        except Exception as e:
            bad.append(f"{os.path.basename(p)}: {e}")
    if "bands" not in names:
        bad.append("data/bands.js missing")
    else:
        ids = [b["id"] for b in read_data_js(os.path.join(SITE, "data", "bands.js"))]
        bad += [f"band_{i}.js missing" for i in ids if f"band_{i}" not in names]
        bad += [f"{n}.js not in the band index" for n in sorted(names - {"bands"} - {f"band_{i}" for i in ids})]
    html = open(os.path.join(SITE, "index.html"), encoding="utf-8").read()
    if 'src="app/gambito.js"' not in html or 'type="module"' in html:
        bad.append("index.html must load app/gambito.js as a classic script")
    if glob.glob(os.path.join(SITE, "data", "*.json")):
        bad.append("leftover data/*.json")
    print(f"check: {len(files)} data files, " + ("OK" if not bad else "PROBLEMS:\n  " + "\n  ".join(bad)))
    return not bad


if __name__ == "__main__":
    convert_json()
    engine_embed()
    bundle()
    sys.exit(0 if check() else 1)
